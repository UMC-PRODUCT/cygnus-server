    CONSTRAINT recruiting_application_interview_question_order_no_check CHECK (order_no >= 0)
);

-- 평가자별 서류·면접 평가를 APPROVED 또는 REJECTED의 제출 완료 결과로 저장한다.
CREATE TABLE public.recruiting_application_evaluation
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_application_id BIGINT                                  NOT NULL,
    evaluator_member_id        BIGINT                                  NOT NULL,
    stage                      VARCHAR(255)                            NOT NULL,
    decision                   VARCHAR(255)                            NOT NULL,
    comment                    VARCHAR(2000),
    submitted_at               TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_recruiting_application_evaluation PRIMARY KEY (id),
    CONSTRAINT uk_recruiting_application_evaluation_application_evaluator_stage
        UNIQUE (recruiting_application_id, evaluator_member_id, stage),
    CONSTRAINT fk_recruiting_application_evaluation_application
        FOREIGN KEY (recruiting_application_id) REFERENCES public.recruiting_application (id),
    CONSTRAINT recruiting_application_evaluation_evaluator_check CHECK (evaluator_member_id > 0),
    CONSTRAINT recruiting_application_evaluation_stage_check CHECK (stage IN ('DOCUMENT', 'INTERVIEW')),
    CONSTRAINT recruiting_application_evaluation_decision_check CHECK (decision IN ('APPROVED', 'REJECTED'))
);

-- 면접 가능 일정 요청부터 확정까지의 일정과 메일 발송·재시도 상태를 저장한다.
CREATE TABLE public.recruiting_interview_schedule
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                    TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                    TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_application_id    BIGINT                                  NOT NULL,
    availability_form_response_id BIGINT,
    status                        VARCHAR(255)                            NOT NULL,
    starts_at                     TIMESTAMP WITH TIME ZONE,
    ends_at                       TIMESTAMP WITH TIME ZONE,
    location                      VARCHAR(255),
    contact_snapshot              VARCHAR(2000)                           NOT NULL,
    request_mail_status           VARCHAR(255)                            NOT NULL,
    request_mail_attempts         INTEGER                                 NOT NULL,
    request_mail_error            VARCHAR(2000),
    request_mail_sent_at          TIMESTAMP WITH TIME ZONE,
    confirmation_mail_status      VARCHAR(255)                            NOT NULL,
    confirmation_mail_attempts    INTEGER                                 NOT NULL,
    confirmation_mail_error       VARCHAR(2000),
    confirmation_mail_sent_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_recruiting_interview_schedule PRIMARY KEY (id),
    CONSTRAINT uk_recruiting_interview_schedule_application UNIQUE (recruiting_application_id),
    CONSTRAINT fk_recruiting_interview_schedule_application
        FOREIGN KEY (recruiting_application_id) REFERENCES public.recruiting_application (id),
    CONSTRAINT recruiting_interview_schedule_status_check CHECK (
        status IN ('AVAILABILITY_REQUESTED', 'AVAILABILITY_SUBMITTED', 'CONFIRMED', 'CANCELLED')
    ),
    CONSTRAINT recruiting_interview_schedule_response_check CHECK (
        availability_form_response_id IS NULL OR availability_form_response_id > 0
    ),
    CONSTRAINT recruiting_interview_schedule_contact_check CHECK (BTRIM(contact_snapshot) <> ''),
    CONSTRAINT recruiting_interview_schedule_state_check CHECK (
        status = 'CANCELLED'
        OR (
            status = 'AVAILABILITY_REQUESTED'
            AND availability_form_response_id IS NULL
            AND starts_at IS NULL
            AND ends_at IS NULL
            AND location IS NULL
        )
        OR (
            status = 'AVAILABILITY_SUBMITTED'
            AND availability_form_response_id IS NOT NULL
            AND starts_at IS NULL
            AND ends_at IS NULL
            AND location IS NULL
        )
        OR (
            status = 'CONFIRMED'
            AND availability_form_response_id IS NOT NULL
            AND starts_at IS NOT NULL
            AND ends_at IS NOT NULL
            AND starts_at < ends_at
            AND location IS NOT NULL
            AND BTRIM(location) <> ''
        )
    ),
    CONSTRAINT recruiting_interview_schedule_mail_attempts_check CHECK (
        request_mail_attempts >= 0 AND confirmation_mail_attempts >= 0
    ),
    CONSTRAINT recruiting_interview_schedule_request_mail_status_check CHECK (
        request_mail_status IN ('PENDING', 'SENT', 'FAILED')
    ),
    CONSTRAINT recruiting_interview_schedule_confirmation_mail_status_check CHECK (
        confirmation_mail_status IN ('PENDING', 'SENT', 'FAILED')
    ),
    CONSTRAINT recruiting_interview_schedule_request_mail_shape_check CHECK (
        (request_mail_status = 'PENDING' AND request_mail_error IS NULL AND request_mail_sent_at IS NULL)
        OR (request_mail_status = 'SENT' AND request_mail_error IS NULL AND request_mail_sent_at IS NOT NULL)
        OR (
            request_mail_status = 'FAILED'
            AND request_mail_error IS NOT NULL
            AND BTRIM(request_mail_error) <> ''
            AND request_mail_sent_at IS NULL
        )
    ),
    CONSTRAINT recruiting_interview_schedule_confirmation_mail_shape_check CHECK (
        (
            confirmation_mail_status = 'PENDING'
            AND confirmation_mail_error IS NULL
            AND confirmation_mail_sent_at IS NULL
        )
        OR (
            confirmation_mail_status = 'SENT'
            AND confirmation_mail_error IS NULL
            AND confirmation_mail_sent_at IS NOT NULL
        )
        OR (
            confirmation_mail_status = 'FAILED'
            AND confirmation_mail_error IS NOT NULL
            AND BTRIM(confirmation_mail_error) <> ''
            AND confirmation_mail_sent_at IS NULL
        )
    )
);

-- 사용자가 구분하는 모집 제목은 같은 Season 안에서 대소문자와 무관하게 중복되지 않도록 한다.
CREATE UNIQUE INDEX uk_recruiting_round_season_title_ci
    ON public.recruiting_round (recruiting_season_id, LOWER(title));

-- Form별 section 정책 조회가 전체 정책 테이블을 순회하지 않도록 연결 인덱스를 생성한다.
CREATE INDEX ix_recruiting_form_section_policy_application_form
    ON public.recruiting_form_section_policy (recruiting_application_form_id);

-- 지원서 상태 기반 운영 조회를 지원한다.
CREATE INDEX ix_recruiting_application_status
    ON public.recruiting_application (status);

-- READY와 REGISTERED가 소비하는 track별 TO를 잠금·집계할 때 사용할 부분 인덱스를 생성한다.
CREATE INDEX ix_recruiting_application_quota_usage
    ON public.recruiting_application (recruiting_round_id, accepted_track, registration_status)
    WHERE registration_status IN ('READY', 'REGISTERED');

-- Round 공통 질문을 활성 여부와 표시 순서로 조회할 수 있도록 인덱스를 생성한다.
CREATE INDEX ix_recruiting_round_interview_question_round_active_order
    ON public.recruiting_round_interview_question (recruiting_round_id, active, order_no, id);

-- 지원자 개별 질문을 활성 여부와 표시 순서로 조회할 수 있도록 인덱스를 생성한다.
CREATE INDEX ix_recruiting_application_interview_question_application_active_order
    ON public.recruiting_application_interview_question (recruiting_application_id, active, order_no, id);

-- 지원서의 전형 단계별 평가 목록 조회를 지원한다.
CREATE INDEX ix_recruiting_application_evaluation_application_stage
    ON public.recruiting_application_evaluation (recruiting_application_id, stage);
