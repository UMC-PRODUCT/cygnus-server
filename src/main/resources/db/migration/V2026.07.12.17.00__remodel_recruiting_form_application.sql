        RAISE EXCEPTION USING
            ERRCODE = 'P0001',
            MESSAGE = 'V2026.07.12.17.00 aborted: recruiting_application and recruiting_application_form must be empty before destructive Recruiting v2 remodeling';
    END IF;
END
