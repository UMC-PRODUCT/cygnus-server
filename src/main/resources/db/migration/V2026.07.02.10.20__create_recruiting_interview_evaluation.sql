CREATE TABLE public.recruiting_evaluation_template
(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                      TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                      TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_application_form_id  BIGINT                                  NOT NULL,
    status                          VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_recruiting_evaluation_template PRIMARY KEY (id),
    CONSTRAINT recruiting_evaluation_template_status_check CHECK (
        status IN ('ACTIVE', 'ARCHIVED')
    )
);

CREATE TABLE public.recruiting_evaluation_criterion
(
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                        TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                        TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_evaluation_template_id BIGINT                                  NOT NULL,
    name                              VARCHAR(100)                            NOT NULL,
    description                       VARCHAR(500),
    score_min                         INTEGER                                 NOT NULL,
    score_max                         INTEGER                                 NOT NULL,
    sort_order                        INTEGER                                 NOT NULL,
    required                          BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_recruiting_evaluation_criterion PRIMARY KEY (id),
    CONSTRAINT uk_recruiting_evaluation_criterion_template_sort UNIQUE (
        recruiting_evaluation_template_id,
        sort_order
    ),
    CONSTRAINT recruiting_evaluation_criterion_score_range_check CHECK (score_min <= score_max)
);

CREATE TABLE public.recruiting_interview_assignment
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_application_id  BIGINT                                  NOT NULL,
    interviewer_member_id      BIGINT                                  NOT NULL,
    starts_at                  TIMESTAMP WITH TIME ZONE                NOT NULL,
    ends_at                    TIMESTAMP WITH TIME ZONE                NOT NULL,
    location                   VARCHAR(255),
    status                     VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_recruiting_interview_assignment PRIMARY KEY (id),
    CONSTRAINT uk_recruiting_interview_assignment_application_interviewer UNIQUE (
        recruiting_application_id,
        interviewer_member_id
    ),
    CONSTRAINT recruiting_interview_assignment_period_check CHECK (starts_at < ends_at),
    CONSTRAINT recruiting_interview_assignment_status_check CHECK (
        status IN ('ASSIGNED', 'CANCELLED')
    )
);

CREATE TABLE public.recruiting_interview_evaluation
(
    id                                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                          TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                          TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_interview_assignment_id  BIGINT                                  NOT NULL,
    recruiting_application_id           BIGINT                                  NOT NULL,
    evaluator_member_id                 BIGINT                                  NOT NULL,
    status                              VARCHAR(255)                            NOT NULL,
    score                               INTEGER,
    comment                             VARCHAR(2000),
    submitted_at                        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_recruiting_interview_evaluation PRIMARY KEY (id),
    CONSTRAINT recruiting_interview_evaluation_status_check CHECK (
        status IN ('DRAFT', 'SUBMITTED')
    )
);

