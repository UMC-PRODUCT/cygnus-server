    ADD CONSTRAINT fk_recruiting_interview_evaluation_assignment
        FOREIGN KEY (recruiting_interview_assignment_id) REFERENCES public.recruiting_interview_assignment (id);

ALTER TABLE public.recruiting_interview_evaluation
    ADD CONSTRAINT fk_recruiting_interview_evaluation_application
        FOREIGN KEY (recruiting_application_id) REFERENCES public.recruiting_application (id);

CREATE UNIQUE INDEX uk_recruiting_interview_evaluation_submitted_application_evaluator
    ON public.recruiting_interview_evaluation (recruiting_application_id, evaluator_member_id)
    WHERE status = 'SUBMITTED';

