    has_rows BOOLEAN;
BEGIN
    FOREACH source_table IN ARRAY ARRAY[
        'recruiting_interview_evaluation',
        'recruiting_interview_assignment',
        'recruiting_evaluation_criterion',
        'recruiting_evaluation_template'
    ] LOOP
        IF TO_REGCLASS('public.' || source_table) IS NOT NULL THEN
            EXECUTE FORMAT('SELECT EXISTS (SELECT 1 FROM public.%I LIMIT 1)', source_table)
                INTO has_rows;
            IF has_rows THEN
                RAISE EXCEPTION USING
                    ERRCODE = 'P0001',
                    MESSAGE = FORMAT(
                        'V2026.07.13.10.00 aborted: source table public.%I must be empty before destructive Recruiting evaluation replacement',
                        source_table
                    );
            END IF;
        END IF;
    END LOOP;
END
$$;

DROP TABLE IF EXISTS public.recruiting_interview_evaluation;
DROP TABLE IF EXISTS public.recruiting_interview_assignment;
DROP TABLE IF EXISTS public.recruiting_evaluation_criterion;
DROP TABLE IF EXISTS public.recruiting_evaluation_template;

CREATE TABLE public.recruiting_application_evaluation
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_application_id BIGINT                                  NOT NULL,
    evaluator_member_id        BIGINT                                  NOT NULL,
    stage                       VARCHAR(255)                            NOT NULL,
    status                      VARCHAR(255)                            NOT NULL,
    decision                    VARCHAR(255),
    comment                     VARCHAR(2000),
    submitted_at                TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_recruiting_application_evaluation PRIMARY KEY (id),
    CONSTRAINT uk_recruiting_application_evaluation_application_evaluator_stage
        UNIQUE (recruiting_application_id, evaluator_member_id, stage),
    CONSTRAINT fk_recruiting_application_evaluation_application
        FOREIGN KEY (recruiting_application_id) REFERENCES public.recruiting_application (id),
    CONSTRAINT recruiting_application_evaluation_evaluator_check
        CHECK (evaluator_member_id > 0),
    CONSTRAINT recruiting_application_evaluation_stage_check
        CHECK (stage IN ('DOCUMENT', 'INTERVIEW')),
    CONSTRAINT recruiting_application_evaluation_status_check
        CHECK (status IN ('DRAFT', 'SUBMITTED')),
    CONSTRAINT recruiting_application_evaluation_decision_check
        CHECK (decision IS NULL OR decision IN ('PASS', 'FAIL', 'WAIT')),
    CONSTRAINT recruiting_application_evaluation_submission_check
        CHECK (
            (status = 'DRAFT' AND submitted_at IS NULL)
            OR (status = 'SUBMITTED' AND decision IS NOT NULL AND submitted_at IS NOT NULL)
        )
);

CREATE INDEX ix_recruiting_application_evaluation_application_stage_status
    ON public.recruiting_application_evaluation (recruiting_application_id, stage, status);

CREATE TABLE public.recruiting_interview_schedule
(
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at                   TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                   TIMESTAMP WITH TIME ZONE                NOT NULL,
    recruiting_application_id   BIGINT                                  NOT NULL,
    availability_form_response_id BIGINT,
    status                       VARCHAR(255)                            NOT NULL,
    starts_at                    TIMESTAMP WITH TIME ZONE,
    ends_at                      TIMESTAMP WITH TIME ZONE,
    location                     VARCHAR(255),
    contact_snapshot             VARCHAR(2000)                           NOT NULL,
    request_mail_status          VARCHAR(255)                            NOT NULL,
    request_mail_attempts        INTEGER                                 NOT NULL,
    request_mail_error           VARCHAR(2000),
    request_mail_sent_at         TIMESTAMP WITH TIME ZONE,
    confirmation_mail_status     VARCHAR(255)                            NOT NULL,
    confirmation_mail_attempts   INTEGER                                 NOT NULL,
    confirmation_mail_error      VARCHAR(2000),
    confirmation_mail_sent_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_recruiting_interview_schedule PRIMARY KEY (id),
    CONSTRAINT uk_recruiting_interview_schedule_application UNIQUE (recruiting_application_id),
    CONSTRAINT fk_recruiting_interview_schedule_application
        FOREIGN KEY (recruiting_application_id) REFERENCES public.recruiting_application (id),
    CONSTRAINT recruiting_interview_schedule_status_check
        CHECK (status IN ('AVAILABILITY_REQUESTED', 'AVAILABILITY_SUBMITTED', 'CONFIRMED')),
    CONSTRAINT recruiting_interview_schedule_response_check
        CHECK (availability_form_response_id IS NULL OR availability_form_response_id > 0),
    CONSTRAINT recruiting_interview_schedule_contact_check
        CHECK (BTRIM(contact_snapshot) <> ''),
    CONSTRAINT recruiting_interview_schedule_state_check
        CHECK (
            (
                status = 'AVAILABILITY_REQUESTED'
                AND availability_form_response_id IS NULL
                AND starts_at IS NULL
                AND ends_at IS NULL
                AND location IS NULL
            )
            OR (
                status = 'AVAILABILITY_SUBMITTED'
                AND availability_form_response_id IS NOT NULL
                AND starts_at IS NULL
                AND ends_at IS NULL
                AND location IS NULL
            )
            OR (
                status = 'CONFIRMED'
                AND availability_form_response_id IS NOT NULL
                AND starts_at IS NOT NULL
                AND ends_at IS NOT NULL
                AND starts_at < ends_at
                AND location IS NOT NULL
                AND BTRIM(location) <> ''
            )
        ),
    CONSTRAINT recruiting_interview_schedule_mail_attempts_check
        CHECK (request_mail_attempts >= 0 AND confirmation_mail_attempts >= 0),
    CONSTRAINT recruiting_interview_schedule_request_mail_status_check
        CHECK (request_mail_status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT recruiting_interview_schedule_confirmation_mail_status_check
        CHECK (confirmation_mail_status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT recruiting_interview_schedule_request_mail_shape_check
        CHECK (
            (request_mail_status = 'PENDING' AND request_mail_error IS NULL AND request_mail_sent_at IS NULL)
            OR (request_mail_status = 'SENT' AND request_mail_error IS NULL AND request_mail_sent_at IS NOT NULL)
            OR (
                request_mail_status = 'FAILED'
                AND request_mail_error IS NOT NULL
                AND BTRIM(request_mail_error) <> ''
                AND request_mail_sent_at IS NULL
            )
        ),
    CONSTRAINT recruiting_interview_schedule_confirmation_mail_shape_check
        CHECK (
            (
                confirmation_mail_status = 'PENDING'
                AND confirmation_mail_error IS NULL
                AND confirmation_mail_sent_at IS NULL
            )
            OR (
                confirmation_mail_status = 'SENT'
                AND confirmation_mail_error IS NULL
                AND confirmation_mail_sent_at IS NOT NULL
            )
            OR (
                confirmation_mail_status = 'FAILED'
                AND confirmation_mail_error IS NOT NULL
                AND BTRIM(confirmation_mail_error) <> ''
                AND confirmation_mail_sent_at IS NULL
            )
        )
);
