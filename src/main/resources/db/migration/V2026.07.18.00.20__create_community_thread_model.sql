    ADD CONSTRAINT report_target_type_check
        CHECK (target_type IN ('POST', 'COMMENT', 'THREAD_MESSAGE')),
    ADD CONSTRAINT fk_report_community_thread
        FOREIGN KEY (thread_id) REFERENCES community_thread (id),
    ADD CONSTRAINT ck_report_reason_code
        CHECK (reason_code IS NULL OR reason_code IN ('SPAM', 'ABUSE', 'INAPPROPRIATE', 'PRIVACY', 'ETC')),
    ADD CONSTRAINT ck_report_thread_message_fields
        CHECK (
            (target_type = 'THREAD_MESSAGE'
                AND thread_id IS NOT NULL
                AND thread_id > 0
                AND reason_code IS NOT NULL)
            OR
            (target_type IN ('POST', 'COMMENT') AND thread_id IS NULL AND reason_code IS NULL)
        );

