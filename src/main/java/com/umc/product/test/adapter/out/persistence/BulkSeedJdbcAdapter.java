package com.umc.product.test.adapter.out.persistence;

import java.sql.Timestamp;
import java.util.List;

import org.springframework.context.annotation.Profile;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import com.umc.product.test.application.port.out.BulkSeedPort;
import com.umc.product.test.application.port.out.dto.BulkSeedBaseIds;
import com.umc.product.test.application.port.out.dto.SeedChallengerPointRow;
import com.umc.product.test.application.port.out.dto.SeedChallengerRow;
import com.umc.product.test.application.port.out.dto.SeedMemberRow;
import com.umc.product.test.application.port.out.dto.SeedNoticeRow;
import com.umc.product.test.application.port.out.dto.SeedScheduleParticipantRow;
import com.umc.product.test.application.port.out.dto.SeedScheduleRow;

import lombok.RequiredArgsConstructor;

/**
 * 벌크 시딩 JDBC 어댑터. 도메인 가드를 우회해 직접 INSERT 하므로 컬럼 계약이 엔티티와 어긋나면
 * 여기가 깨진다 — 스키마(Flyway) 변경 시 이 파일의 SQL 을 함께 검토할 것.
 * <p>
 * id 는 서비스가 명시적으로 부여한다(전 테이블 GENERATED BY DEFAULT IDENTITY 라 허용).
 * challenger_point / schedule_participant 는 다른 행이 FK 로 참조하지 않으므로 identity 기본값을 쓴다.
 */
@Component
@Profile("seeder")
@RequiredArgsConstructor
public class BulkSeedJdbcAdapter implements BulkSeedPort {

    private static final int JDBC_BATCH_SIZE = 500;
    private static final String[] IDENTITY_SYNC_TABLES = {"member", "challenger", "schedule", "notice"};
    private static final String[] ANALYZE_TABLES = {
        "member", "challenger", "challenger_point",
        "schedule", "schedule_tags", "schedule_participant",
        "notice", "notice_target"
    };

    private final JdbcTemplate jdbcTemplate;

    @Override
    public BulkSeedBaseIds currentMaxIds() {
        return new BulkSeedBaseIds(
            maxId("member"), maxId("challenger"), maxId("schedule"), maxId("notice"));
    }

    private long maxId(String table) {
        Long max = jdbcTemplate.queryForObject("SELECT COALESCE(MAX(id), 0) FROM " + table, Long.class);
        return max == null ? 0L : max;
    }

    @Override
    public void insertMembers(List<SeedMemberRow> rows) {
        jdbcTemplate.batchUpdate(
            "INSERT INTO member (id, name, nickname, email, school_id, status, created_at, updated_at) "
                + "VALUES (?, ?, ?, ?, ?, 'ACTIVE', now(), now())",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.id());
                ps.setString(2, row.name());
                ps.setString(3, row.nickname());
                ps.setString(4, row.email());
                ps.setObject(5, row.schoolId());
            });
    }

    @Override
    public void insertChallengers(List<SeedChallengerRow> rows) {
        jdbcTemplate.batchUpdate(
            "INSERT INTO challenger (id, member_id, part, tracks, gisu_id, status, created_at, updated_at) "
                + "VALUES (?, ?, ?, ?, ?, 'ACTIVE', now(), now())",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.id());
                ps.setLong(2, row.memberId());
                ps.setString(3, row.part() == null ? null : row.part().name());
                ps.setArray(4, ps.getConnection().createArrayOf(
                    "text", row.tracks().stream().map(Enum::name).toArray(String[]::new)));
                ps.setLong(5, row.gisuId());
            });
    }

    @Override
    public void insertChallengerPoints(List<SeedChallengerPointRow> rows) {
        jdbcTemplate.batchUpdate(
            "INSERT INTO challenger_point (challenger_id, point, description, created_at, updated_at) "
                + "VALUES (?, ?, ?, now(), now())",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.challengerId());
                ps.setString(2, row.pointType().name());
                ps.setString(3, row.description());
            });
    }

    @Override
    public void insertSchedules(List<SeedScheduleRow> rows) {
        jdbcTemplate.batchUpdate(
            "INSERT INTO schedule (id, name, author_member_id, starts_at, ends_at, created_at, updated_at) "
                + "VALUES (?, ?, ?, ?, ?, now(), now())",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.id());
                ps.setString(2, row.name());
                ps.setLong(3, row.authorMemberId());
                ps.setTimestamp(4, Timestamp.from(row.startsAt()));
                ps.setTimestamp(5, Timestamp.from(row.endsAt()));
            });
        // tags 는 도메인 필수(min 1) — GENERAL 하나를 같이 넣는다.
        jdbcTemplate.batchUpdate(
            "INSERT INTO schedule_tags (schedule_id, tag) VALUES (?, 'GENERAL')",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> ps.setLong(1, row.id()));
    }

    @Override
    public void insertScheduleParticipants(List<SeedScheduleParticipantRow> rows) {
        jdbcTemplate.batchUpdate(
            "INSERT INTO schedule_participant (member_id, schedule_id, created_at, updated_at) "
                + "VALUES (?, ?, now(), now())",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.memberId());
                ps.setLong(2, row.scheduleId());
            });
    }

    @Override
    public void insertNotices(List<SeedNoticeRow> rows, long targetGisuId) {
        jdbcTemplate.batchUpdate(
            "INSERT INTO notice (id, title, content, author_member_id, view_count, "
                + "should_send_notification, must_read, created_at, updated_at) "
                + "VALUES (?, ?, ?, ?, 0, false, false, ?, ?)",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.id());
                ps.setString(2, row.title());
                ps.setString(3, row.content());
                ps.setLong(4, row.authorMemberId());
                ps.setTimestamp(5, Timestamp.from(row.createdAt()));
                ps.setTimestamp(6, Timestamp.from(row.createdAt()));
            });
        jdbcTemplate.batchUpdate(
            "INSERT INTO notice_target (notice_id, target_gisu_id, target_notice_tab, created_at, updated_at) "
                + "VALUES (?, ?, 'CHALLENGER', now(), now())",
            rows, JDBC_BATCH_SIZE,
            (ps, row) -> {
                ps.setLong(1, row.id());
                ps.setLong(2, targetGisuId);
            });
    }

    @Override
    public void finalizeBulkLoad() {
        // 명시 id 로 적재하면 identity 시퀀스가 뒤처진 채 남는다 — 동기화하지 않으면 이후
        // 앱 경유 INSERT(api 시더·실제 command API)가 중복 키로 터진다.
        for (String table : IDENTITY_SYNC_TABLES) {
            jdbcTemplate.queryForObject(
                "SELECT setval(pg_get_serial_sequence('%s', 'id'), (SELECT COALESCE(MAX(id), 1) FROM %s))"
                    .formatted(table, table),
                Long.class);
        }
        // 갓 적재한 테이블은 통계가 비어 플래너가 엉뚱한 실행 계획을 고를 수 있다 — 측정 전에 ANALYZE.
        for (String table : ANALYZE_TABLES) {
            jdbcTemplate.execute("ANALYZE " + table);
        }
    }
}
