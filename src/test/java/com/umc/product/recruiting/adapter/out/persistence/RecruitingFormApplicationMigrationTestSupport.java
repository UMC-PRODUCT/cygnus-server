package com.umc.product.recruiting.adapter.out.persistence;

import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;

import org.junit.jupiter.api.BeforeEach;
import org.springframework.core.io.ClassPathResource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;

abstract class RecruitingFormApplicationMigrationTestSupport {

    private static final String MIGRATION_PATH =
        "db/migration/V2026.07.12.17.00__remodel_recruiting_form_application.sql";

    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:18-alpine");

    @BeforeEach
    void setUpLegacySchema() throws Exception {
        try (Connection connection = POSTGRES.createConnection(""); var statement = connection.createStatement()) {
            statement.execute("DROP SCHEMA public CASCADE");
            statement.execute("CREATE SCHEMA public");
            statement.execute("CREATE TABLE unrelated_domain_sentinel (id BIGINT PRIMARY KEY)");
            statement.execute("INSERT INTO unrelated_domain_sentinel VALUES (1)");
            statement.execute("""
                CREATE TABLE recruiting_round (
                    id BIGINT PRIMARY KEY,
                    recruitable_tracks TEXT[] NOT NULL,
                    second_choice_enabled BOOLEAN NOT NULL
                )
                """);
            statement.execute("""
                CREATE TABLE recruiting_application_form (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at TIMESTAMPTZ NOT NULL,
                    updated_at TIMESTAMPTZ NOT NULL,
                    recruiting_round_id BIGINT NOT NULL REFERENCES recruiting_round(id),
                    form_id BIGINT NOT NULL,
                    track VARCHAR(255) NOT NULL,
                    status VARCHAR(255) NOT NULL,
                    CONSTRAINT uk_recruiting_application_form_round_form
                        UNIQUE (recruiting_round_id, form_id)
                )
                """);
            statement.execute("""
                CREATE TABLE recruiting_application (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at TIMESTAMPTZ NOT NULL,
                    updated_at TIMESTAMPTZ NOT NULL,
                    recruiting_round_id BIGINT NOT NULL REFERENCES recruiting_round(id),
                    recruiting_application_form_id BIGINT NOT NULL REFERENCES recruiting_application_form(id),
                    form_response_id BIGINT NOT NULL UNIQUE,
                    applicant_member_id BIGINT,
                    applicant_identity_key VARCHAR(128) NOT NULL,
                    application_no VARCHAR(64) NOT NULL,
                    masked_email VARCHAR(255),
                    status VARCHAR(255) NOT NULL,
                    registration_status VARCHAR(255) NOT NULL,
                    submitted_at TIMESTAMPTZ,
                    status_changed_member_id BIGINT,
                    status_change_reason VARCHAR(255),
                    status_changed_at TIMESTAMPTZ,
                    CONSTRAINT uk_recruiting_application_application_no UNIQUE (application_no)
                )
                """);
            statement.execute("""
                CREATE TABLE recruiting_application_interview_question (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    recruiting_application_id BIGINT NOT NULL REFERENCES recruiting_application(id),
                    content TEXT NOT NULL
                )
                """);
            statement.execute("""
                INSERT INTO recruiting_round VALUES
                    (1, ARRAY['PLAN', 'DESIGN'], TRUE),
                    (2, ARRAY['PLAN', 'DESIGN'], TRUE);
                INSERT INTO recruiting_application_form (
                    created_at, updated_at, recruiting_round_id, form_id, track, status
                ) VALUES (CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 1, 100, 'PLAN', 'DRAFT');
                INSERT INTO recruiting_application (
                    created_at, updated_at, recruiting_round_id, recruiting_application_form_id,
                    form_response_id, applicant_identity_key, application_no, status, registration_status
                ) VALUES (
                    CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 1, 1, 1000, 'legacy', 'APP-1', 'DRAFT', 'NOT_READY'
                );
                INSERT INTO recruiting_application_interview_question (recruiting_application_id, content)
                VALUES (1, 'legacy');
                """);
        }
    }

    void executeMigration() throws Exception {
        String sql = new ClassPathResource(MIGRATION_PATH).getContentAsString(StandardCharsets.UTF_8);
        try (Connection connection = POSTGRES.createConnection(""); var statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    void clearLegacyRecruitingData() throws Exception {
        try (Connection connection = POSTGRES.createConnection(""); var statement = connection.createStatement()) {
            statement.execute("TRUNCATE TABLE recruiting_application_form, recruiting_application CASCADE");
        }
    }

    String applicationInsert(String values) {
        return """
            INSERT INTO recruiting_application (
                created_at, updated_at, recruiting_round_id, recruiting_application_form_id,
                form_response_id, applicant_member_id, applicant_name, applicant_email,
                first_choice, second_choice, privacy_term_id, privacy_agreed_at,
                application_key, accepted_track, status, registration_status
            ) VALUES (CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, %s, 'DRAFT', 'NOT_READY')
            """.formatted(values.strip());
    }

    void assertApplicationRejected(java.sql.Statement statement, String values) {
        assertThatThrownBy(() -> statement.executeUpdate(applicationInsert(values)))
            .isInstanceOf(Exception.class);
    }
}
